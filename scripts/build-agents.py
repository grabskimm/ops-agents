#!/usr/bin/env python3
"""Generate .claude/agents/<name>.md and .codex/agents/<name>.toml from agents.json + prompts/<name>.md.

Run from the repo root:  python3 scripts/build-agents.py
Generated files are committed so both runtimes work without a build step; re-run after editing a prompt.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "agents.json"
PROMPTS = ROOT / "prompts"
CLAUDE_DIR = ROOT / ".claude" / "agents"
CODEX_DIR = ROOT / ".codex" / "agents"

HEADER = "<!-- GENERATED by scripts/build-agents.py from prompts/{name}.md and agents.json — do not edit here -->\n"
TOML_HEADER = "# GENERATED by scripts/build-agents.py from prompts/{name}.md and agents.json — do not edit here\n"


def yaml_list(items):
    return "[" + ", ".join(items) + "]"


def claude_agent(name, spec, body):
    c = spec["claude"]
    lines = [
        "---",
        f"name: {name}",
        "description: " + json.dumps(spec["description"]),  # JSON string is valid YAML; safe with colons/quotes
        f"model: {c['model']}",
        ("tools:\n" + "\n".join(f"  - {x}" for x in c["tools"])) if any("," in x for x in c["tools"]) else f"tools: {', '.join(c['tools'])}",
    ]
    if c.get("disallowedTools"):
        lines.append(f"disallowedTools: {', '.join(c['disallowedTools'])}")
    if c.get("mcpServers"):
        lines.append(f"mcpServers: {yaml_list(c['mcpServers'])}")
    if c.get("skills"):
        lines.append(f"skills: {yaml_list(c['skills'])}")
    if c.get("maxTurns"):
        lines.append(f"maxTurns: {c['maxTurns']}")
    lines.append("---")
    # Frontmatter must start on line 1; the generated-file marker goes after it.
    return "\n".join(lines) + "\n" + HEADER.format(name=name) + "\n" + body


def toml_str(s):
    # Triple-quoted basic string; escape a closing triple quote if a prompt ever contains one.
    return '"""\n' + s.replace('"""', '\\"\\"\\"') + '"""'


def codex_agent(name, spec, body):
    x = spec["codex"]
    toml_name = name.replace("-", "_")
    extra = ""
    if x.get("allowed_mcp"):
        extra = (
            "\n\n## Runtime (Codex)\n"
            f"Use only these MCP servers: {', '.join(x['allowed_mcp'])}. "
            "Do not call any other MCP server even though the parent session exposes it. "
            + ("Do not edit files." if spec["tier"] == "observe" or spec["tier"].startswith("observe") else "")
        )
    out = [
        TOML_HEADER.format(name=name),
        f'name = "{toml_name}"',
        f'description = "{spec["description"]}"',
        f'model = "{x["model"]}"',
        f'model_reasoning_effort = "{x["model_reasoning_effort"]}"',
        f"developer_instructions = {toml_str(body + extra)}",
    ]
    feats = x.get("features") or {}
    if feats:
        out.append("\n[features]")
        for k, v in feats.items():
            out.append(f"{k} = {'true' if v else 'false'}")
    return "\n".join(out) + "\n"


def main():
    manifest = json.loads(MANIFEST.read_text())
    CLAUDE_DIR.mkdir(parents=True, exist_ok=True)
    CODEX_DIR.mkdir(parents=True, exist_ok=True)
    missing = []
    for name, spec in manifest["agents"].items():
        if name.startswith("_"):
            continue
        p = PROMPTS / f"{name}.md"
        if not p.exists():
            missing.append(str(p))
            continue
        body = p.read_text().rstrip() + "\n"
        (CLAUDE_DIR / f"{name}.md").write_text(claude_agent(name, spec, body))
        (CODEX_DIR / f"{name}.toml").write_text(codex_agent(name, spec, body))
        print(f"wrote {name}")
    if missing:
        print("missing prompts:", *missing, file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
